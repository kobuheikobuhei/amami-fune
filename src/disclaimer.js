// 免責の文言。仕様 §4「免責文を全ページ・全記事に固定表示」の実体。
//
// 4つの生成器（記事・航路の常設ページ・日別ページ・台風ページ）が同じ文を
// それぞれ持っていた。文を直すたびに4か所を直すことになり、
// 1か所だけ古いまま残るのが目に見えているので、ここに集める。
//
// 言いたいことは3つある。
//
//  1. ここは各社の発表を機械が写している場所で、発表元ではない
//  2. 写した時点と今とでは違っていることがある
//  3. 参考として個人で使うもので、これを見て動いた結果の責任は負えない
//
// 3つ目は、同じ性質の情報を出している他所（KKBの交通情報＝九州のりものinfo）が
// 断っているのと同じ趣旨で、文言はこちらで書き起こしている。
//
// 「最終的な運航可否は必ず各社公式サイトでご確認ください」は仕様が字句で
// 指定している。言い換えずにこのまま残す。
//
// 記事には1行だけ置く。記事は発表1件ぶんの短いもので、
// そこに箇条書きの断り書きを重ねると本文より長くなる。
// 常設ページ（航路・日別・台風）には詳しいほうを置く。

/** 全ページ・全記事の末尾に置く1行 */
export const DISCLAIMER =
  '当サイトは各社の公式発表をもとに自動で掲載している参考情報です。'
  + '個人でご利用になる際の目安としてお使いいただき、'
  + '最終的な運航可否は必ず各社公式サイトでご確認ください。';

const NOTE_STYLE = 'font-size:0.9em;color:#555;line-height:1.7';

/** 記事の末尾。区切り線と1行だけ */
export function buildDisclaimerLine() {
  return '<hr>'
    + '<p style="' + NOTE_STYLE + '">' + DISCLAIMER + '</p>';
}

/** 常設ページの末尾。1行に続けて、詳しい断り書きを置く */
export function buildDisclaimerBlock() {
  return buildDisclaimerLine()
    + '<h3 style="font-size:1.05em;margin-bottom:0.4em">ご利用にあたって</h3>'
    + '<ul style="' + NOTE_STYLE + ';padding-left:1.2em;margin-top:0">'
    + '<li>当サイトは、各社が公式サイトで発表した内容を自動で集めて掲載しています。'
    + '発表から掲載までには時間差があり、掲載の後に発表が変わることもあるため、'
    + '実際の運航状況と異なる場合があります。</li>'
    + '<li>ご乗船やご旅行の判断は、各社公式サイトの案内、または各社へのお問い合わせでお願いします。</li>'
    + '<li>この情報をご利用になったことで生じた損害について、当サイトは責任を負いかねます。</li>'
    + '</ul>';
}
